# Запаковывать export/snapshot в итоговый zip после прохода
MAKE_SNAPSHOT_ZIP = True

# Инкрементальная (недельная) выгрузка.
# "auto" — если есть предыдущий снимок (data/state.json), работает инкрементально:
#   ALL ACTIVE + всё изменённое с прошлого снимка (новые/закрытые/технические);
# "full" — всегда полный проход по фильтру периода;
# "incremental" — принудительно инкрементально (без прошлого снимка = full).
EXPORT_TYPE = "auto"
# Страховочное перекрытие окна изменений (часы): запрашиваем изменения
# с (прошлый снимок - overlap), дубли убираются по ID.
INCREMENTAL_OVERLAP_HOURS = 24

# Повторная выгрузка закрытых сделок (реестр data/registry.json).
# False (по умолчанию): сделка, один раз выгруженная в закрытой/технической
# стадии, в следующие еженедельные пакеты НЕ попадает — никаких дублей.
# True: если закрытая сделка ИЗМЕНИЛАСЬ после прошлой выгрузки (новый коммент,
# документ и т.п.) — выгрузить её ещё раз.
REEXPORT_CLOSED_ON_CHANGE = False

# Префиксы в именах файлов (для файловой индексации в LEX'S).
FILE_BRAND = "LEXS"       # LEXS_DEAL_... / LEXS_SALES_...
# Страна берётся из ПОЛЯ СДЕЛКИ (РБ/РФ): код страны подставляется в имя
# файла каждой сделки. Поле находится автоматически по названию («страна»),
# либо задайте его код явно, напр. COUNTRY_FIELD = "UF_CRM_1234567890".
