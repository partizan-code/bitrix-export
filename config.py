DEALS_LIMIT = 0       # 0 = без лимита; 20 — для тестовой выборки

# ---------------------------------------------------------------- лиды
PROCESS_LEADS = True   # выгружать лиды параллельно со сделками
LEAD_IDS = []          # [] = все лиды; иначе список ID
